function transformPoint(point: GoPoint, size: number, variant: number): GoPoint {
  if (variant === 1) return { row: point.col, col: size - 1 - point.row };
  if (variant === 2) return { row: point.row, col: size - 1 - point.col };
  return point;
}

function choiceVariant(seed: ChoiceSeed, level: number, variant: number): GoChoiceQuestion {
  const shift = variant % seed.options.length;
  const options = [...seed.options.slice(shift), ...seed.options.slice(0, shift)];
  const promptPrefix = ["课堂判断", "实战复盘", "讲给同学听"][variant];
  return {
    id: `go-l${level}-${seed.family}-v${variant + 1}`,
    family: seed.family,
    category: seed.category,
    prompt: `${promptPrefix}：${seed.prompt}`,
    options,
    correct: (seed.correct - shift + seed.options.length) % seed.options.length,
    explanation: seed.explanation,
    type: "choice",
  };
}

function boardVariant(seed: BoardSeed, level: number, variant: number): GoBoardQuestion {
  const stones: GoSetupStone[] = seed.stones.map(([row, col, color]) => ({
    ...transformPoint({ row, col }, seed.boardSize, variant),
    color,
  }));
  return {
    id: `go-l${level}-${seed.family}-v${variant + 1}`,
    family: seed.family,
    category: seed.category,
    prompt: `${seed.prompt}（请在棋盘上落子）`,
    explanation: seed.explanation,
    type: "board",
    boardSize: seed.boardSize,
    stones,
    correctMoves: seed.correctMoves.map(([row, col]) => transformPoint({ row, col }, seed.boardSize, variant)),
    sequence: (seed.sequence ?? seed.correctMoves).map(([row, col]) => transformPoint({ row, col }, seed.boardSize, variant)),
    toPlay: seed.toPlay,
  };
}

export const goQuestionBanks: Record<number, GoQuestion[]> = Object.fromEntries(
  Object.entries(levelSeeds).map(([levelKey, seeds]) => {
    const level = Number(levelKey);
    const questions = seeds.flatMap((seed) => [0, 1, 2].map((variant) => (
      seed.type === "choice" ? choiceVariant(seed, level, variant) : boardVariant(seed, level, variant)
    )));
    if (seeds.length !== 10 || questions.length !== 30) {
      throw new Error(`围棋第 ${level} 级题库必须由 10 个知识家族扩展为 30 题。`);
    }
    return [level, questions];
  }),
);

for (const [level, questions] of Object.entries(goQuestionBanks)) {
  for (const question of questions) {
    if (question.type !== "board") continue;
    const occupied = new Set(question.stones.map((stone) => `${stone.row},${stone.col}`));
    if (question.correctMoves.some((point) => occupied.has(`${point.row},${point.col}`))) {
      throw new Error(`围棋第 ${level} 级题目 ${question.id} 的正确落点已被占用。`);
    }
    if (question.stones.some((stone) => stone.row < 0 || stone.col < 0 || stone.row >= question.boardSize || stone.col >= question.boardSize)) {
      throw new Error(`围棋第 ${level} 级题目 ${question.id} 有棋子超出棋盘。`);
    }
  }
}

function shuffle<T>(items: T[]) {
  const result = [...items];
  for (let index = result.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(Math.random() * (index + 1));
    [result[index], result[swap]] = [result[swap], result[index]];
  }
  return result;
}

export function buildGoAttempt(level: number, familyFilter?: string[]) {
  const bank = goQuestionBanks[level] ?? goQuestionBanks[1];
  const familyNames = familyFilter?.length
    ? [...new Set(familyFilter)]
    : [...new Set(bank.map((question) => question.family))];
  return shuffle(familyNames).flatMap((family) => {
    const variants = bank.filter((question) => question.family === family);
    return variants.length ? [variants[Math.floor(Math.random() * variants.length)]] : [];
  }).slice(0, 10);
}
