function point(tuple: MoveTuple): GoPoint {
  return { row: tuple[0], col: tuple[1] };
}

function transformPoint(input: GoPoint, size: number, variant: number): GoPoint {
  switch (variant) {
    case 1: return { row: input.col, col: size - 1 - input.row };
    case 2: return { row: size - 1 - input.row, col: size - 1 - input.col };
    case 3: return { row: size - 1 - input.col, col: input.row };
    case 4: return { row: input.row, col: size - 1 - input.col };
    case 5: return { row: input.col, col: input.row };
    default: return input;
  }
}

type DirectionChar = "上" | "下" | "左" | "右";

function transformDirectionChar(direction: DirectionChar, variant: number): DirectionChar {
  const maps: Array<Record<DirectionChar, DirectionChar>> = [
    { 上: "上", 下: "下", 左: "左", 右: "右" },
    { 上: "右", 下: "左", 左: "上", 右: "下" },
    { 上: "下", 下: "上", 左: "右", 右: "左" },
    { 上: "左", 下: "右", 左: "下", 右: "上" },
    { 上: "上", 下: "下", 左: "右", 右: "左" },
    { 上: "左", 下: "右", 左: "上", 右: "下" },
  ];
  return maps[variant]?.[direction] ?? direction;
}

function canonicalDiagonal(first: DirectionChar, second: DirectionChar) {
  const horizontal = [first, second].find((item) => item === "左" || item === "右");
  const vertical = [first, second].find((item) => item === "上" || item === "下");
  return horizontal && vertical ? `${horizontal}${vertical}` : `${first}${second}`;
}

function canonicalAxisPair(first: DirectionChar, second: DirectionChar) {
  const values = new Set([first, second]);
  if (values.has("上") && values.has("下")) return "上下";
  if (values.has("左") && values.has("右")) return "左右";
  return `${first}${second}`;
}

function transformDirectionalText(value: string, variant: number) {
  if (variant === 0) return value;
  const protectedPhrases: string[] = [];
  const protect = (replacement: string) => {
    const token = `\uE000${protectedPhrases.length}\uE001`;
    protectedPhrases.push(replacement);
    return token;
  };

  let text = value.replace(/(左上|右上|左下|右下)/g, (match) => {
    const first = transformDirectionChar(match[0] as DirectionChar, variant);
    const second = transformDirectionChar(match[1] as DirectionChar, variant);
    return protect(canonicalDiagonal(first, second));
  });
  text = text.replace(/(上下|左右)/g, (match) => protect(canonicalAxisPair(
    transformDirectionChar(match[0] as DirectionChar, variant),
    transformDirectionChar(match[1] as DirectionChar, variant),
  )));
  text = text.replace(/([上下左右])、([上下左右])/g, (_match, first: DirectionChar, second: DirectionChar) => protect(
    `${transformDirectionChar(first, variant)}、${transformDirectionChar(second, variant)}`,
  ));
  text = text.replace(/(向|往|从|沿)([上下左右])/g, (_match, prefix: string, direction: DirectionChar) => (
    protect(`${prefix}${transformDirectionChar(direction, variant)}`)
  ));
  text = text.replace(/([上下左右])(方|侧|边|角|路)/g, (_match, direction: DirectionChar, suffix: string) => (
    protect(`${transformDirectionChar(direction, variant)}${suffix}`)
  ));

  return text.replace(/\uE000(\d+)\uE001/g, (_match, index: string) => protectedPhrases[Number(index)] ?? "");
}

function setupSeedBoard(seed: PuzzleSeed): GoBoardState {
  const board = createBoard(seed.boardSize);
  const occupied = new Set<string>();
  for (const [row, col, color] of seed.stones) {
    if (row < 0 || col < 0 || row >= seed.boardSize || col >= seed.boardSize) {
      throw new Error(`${seed.family} 有棋子超出 ${seed.boardSize} 路棋盘。`);
    }
    const key = `${row},${col}`;
    if (occupied.has(key)) throw new Error(`${seed.family} 在 ${key} 重复摆子。`);
    occupied.add(key);
    board[row][col] = color;
  }
  return board;
}

function validateSolutionLine(seed: PuzzleSeed, line: MoveTuple[], lineIndex: number) {
  if (!line.length) throw new Error(`${seed.family} 第 ${lineIndex + 1} 条推荐变化为空。`);
  let board = setupSeedBoard(seed);
  const history = [boardHash(board)];
  for (let ply = 0; ply < line.length; ply += 1) {
    const color = (ply % 2 === 0 ? seed.toPlay : seed.toPlay === 1 ? 2 : 1) as 1 | 2;
    const move = point(line[ply]);
    const result = playMove(board, color, move, history);
    if (!result.valid) {
      throw new Error(`${seed.family} 推荐变化 ${lineIndex + 1} 第 ${ply + 1} 手 ${move.row},${move.col} 非法：${result.reason}`);
    }
    board = result.board;
    history.push(boardHash(board));
  }
}

for (let level = 1; level <= 10; level += 1) {
  const seeds = levelSeeds[level];
  if (!seeds || seeds.length !== 10) {
    throw new Error(`围棋第 ${level} 级必须包含 10 个原创棋谱主题，当前为 ${seeds?.length ?? 0}。`);
  }
  const families = new Set(seeds.map((seed) => seed.family));
  if (families.size !== seeds.length) throw new Error(`围棋第 ${level} 级存在重复题目家族。`);
  for (const seed of seeds) {
    setupSeedBoard(seed);
    seed.solutionLines.forEach((line, index) => validateSolutionLine(seed, line, index));
  }
}

function buildQuestion(seed: PuzzleSeed, level: number, variant: number): GoBoardQuestion {
  const transform = (move: MoveTuple) => transformPoint(point(move), seed.boardSize, variant);
  const text = (value: string) => transformDirectionalText(value, variant);
  const stones: GoSetupStone[] = seed.stones.map(([row, col, color]) => ({
    ...transformPoint({ row, col }, seed.boardSize, variant),
    color,
  }));
  const solutionLines = seed.solutionLines.map((line) => line.map(transform));
  const refutations: GoPuzzleRefutation[] = seed.refutations.map((item) => ({
    move: transform(item.move),
    response: item.response.map(transform),
    explanation: text(item.explanation),
  }));

  return {
    id: `go-l${level}-${seed.family}-v${variant + 1}`,
    family: seed.family,
    category: seed.category,
    prompt: text(seed.prompt),
    explanation: text(seed.explanation),
    type: "board",
    task: seed.task,
    boardSize: seed.boardSize,
    stones,
    toPlay: seed.toPlay,
    solutionLines,
    stepNotes: (seed.stepNotes.length ? seed.stepNotes : [seed.explanation]).map(text),
    hint: text(seed.hint),
    success: `推荐变化成立：${text(seed.explanation)}`,
    failure: `这手没有抓住「${seed.category}」的要点。先看绿色推荐点，再按编号复盘完整变化。`,
    refutations,
  };
}

